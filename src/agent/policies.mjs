export function getResponseMode(id = DEFAULT_RESPONSE_MODE) {
  const mode = MODES.find((entry) => entry.id === id);
  if (!mode) throw new RangeError(`Invalid responseMode. Expected: ${MODES.map((entry) => entry.id).join(', ')}`);
  return { ...mode, profile: getAgentProfile(id) };
}

export function responseModeSummaries() {
  return MODES.map(({ id, title, description }) => ({ id, title, description, profile: getAgentProfile(id) }));
}

